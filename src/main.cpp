/*
 * Radar BLE bridge - phase 1
 *
 * Brings up BTstack on the Pico 2 W (CYW43439), advertises the custom
 * Radar Bridge service and notifies a heartbeat counter once a second
 * to any phone that subscribes.
 *
 * Threading: pico_cyw43_arch_none runs BTstack in the background
 * (async context driven by interrupts). Everything that touches
 * BTstack - callbacks and the timer below - runs in that context, so
 * no extra locking is needed. main() only initialises and then idles.
 */

#include <cstdint>
#include <cstdio>

#include "btstack.h"
#include "pico/cyw43_arch.h"
#include "pico/stdlib.h"

#include "radar_gatt.h" // generated from radar_gatt.gatt

namespace {

constexpr uint32_t kHeartbeatMs = 1000;

/* Handles generated by the GATT compiler for the heartbeat characteristic */
constexpr uint16_t kCounterValueHandle =
    ATT_CHARACTERISTIC_F5D30005_3515_47D6_879D_3E34DE8F197A_01_VALUE_HANDLE;
constexpr uint16_t kCounterCccHandle =
    ATT_CHARACTERISTIC_F5D30005_3515_47D6_879D_3E34DE8F197A_01_CLIENT_CONFIGURATION_HANDLE;

/*
 * Advertising data, 31 bytes max:
 *   flags (3) + complete local name "RadarBLE" (10)
 *   + complete list of 128-bit service UUIDs (18) = 31
 * The UUID is stored little-endian (byte order reversed from the string).
 */
const uint8_t kAdvData[] = {
    0x02, BLUETOOTH_DATA_TYPE_FLAGS, 0x06,
    0x09, BLUETOOTH_DATA_TYPE_COMPLETE_LOCAL_NAME, 'R', 'a', 'd', 'a', 'r', 'B', 'L', 'E',
    0x11, BLUETOOTH_DATA_TYPE_COMPLETE_LIST_OF_128_BIT_SERVICE_CLASS_UUIDS,
    0x7A, 0x19, 0x8F, 0xDE, 0x34, 0x3E, 0x9D, 0x87,
    0xD6, 0x47, 0x15, 0x35, 0x01, 0x00, 0xD3, 0xF5,
};
static_assert(sizeof(kAdvData) <= 31, "advertising data too long");

btstack_packet_callback_registration_t hci_event_registration;
btstack_timer_source_t heartbeat_timer;

hci_con_handle_t con_handle = HCI_CON_HANDLE_INVALID;
bool counter_notify_enabled = false;
uint32_t counter = 0;
bool led_on = false;

void start_advertising()
{
    /* 100-200 ms advertising interval, in 0.625 ms units */
    const uint16_t adv_int_min = 160;
    const uint16_t adv_int_max = 320;
    const uint8_t adv_type = 0; /* ADV_IND: connectable, undirected */
    bd_addr_t null_addr = {};

    gap_advertisements_set_params(adv_int_min, adv_int_max, adv_type, 0, null_addr, 0x07, 0x00);
    gap_advertisements_set_data(sizeof(kAdvData), const_cast<uint8_t *>(kAdvData));
    gap_advertisements_enable(1);
    printf("Advertising as RadarBLE\n");
}

void packet_handler(uint8_t packet_type, uint16_t channel, uint8_t *packet, uint16_t size)
{
    (void)channel;
    (void)size;

    if (packet_type != HCI_EVENT_PACKET) {
        return;
    }

    switch (hci_event_packet_get_type(packet)) {
    case BTSTACK_EVENT_STATE: {
        if (btstack_event_state_get_state(packet) != HCI_STATE_WORKING) {
            break;
        }
        bd_addr_t local_addr;
        gap_local_bd_addr(local_addr);
        printf("BTstack up, address %s\n", bd_addr_to_str(local_addr));
        start_advertising();
        break;
    }

    case ATT_EVENT_CONNECTED:
        con_handle = att_event_connected_get_handle(packet);
        printf("Connected, handle 0x%04x\n", con_handle);
        break;

    case ATT_EVENT_MTU_EXCHANGE_COMPLETE:
        printf("MTU exchanged: %u\n", att_event_mtu_exchange_complete_get_MTU(packet));
        break;

    case ATT_EVENT_DISCONNECTED:
        printf("Disconnected\n");
        con_handle = HCI_CON_HANDLE_INVALID;
        counter_notify_enabled = false;
        /* BTstack resumes advertising by itself after a disconnect */
        break;

    case ATT_EVENT_CAN_SEND_NOW: {
        if (!counter_notify_enabled || con_handle == HCI_CON_HANDLE_INVALID) {
            break;
        }
        uint8_t value[4];
        little_endian_store_32(value, 0, counter);
        att_server_notify(con_handle, kCounterValueHandle, value, sizeof(value));
        break;
    }

    default:
        break;
    }
}

uint16_t att_read_callback(hci_con_handle_t connection_handle, uint16_t att_handle,
                           uint16_t offset, uint8_t *buffer, uint16_t buffer_size)
{
    (void)connection_handle;

    if (att_handle == kCounterValueHandle) {
        uint8_t value[4];
        little_endian_store_32(value, 0, counter);
        return att_read_callback_handle_blob(value, sizeof(value), offset, buffer, buffer_size);
    }

    return 0;
}

int att_write_callback(hci_con_handle_t connection_handle, uint16_t att_handle,
                       uint16_t transaction_mode, uint16_t offset, uint8_t *buffer,
                       uint16_t buffer_size)
{
    (void)transaction_mode;
    (void)offset;

    if (att_handle == kCounterCccHandle && buffer_size >= 2) {
        counter_notify_enabled = little_endian_read_16(buffer, 0) ==
                                 GATT_CLIENT_CHARACTERISTICS_CONFIGURATION_NOTIFICATION;
        con_handle = connection_handle;
        printf("Counter notifications %s\n", counter_notify_enabled ? "on" : "off");
    }

    return 0;
}

/* Runs in the BTstack context, so it may call BTstack directly */
void heartbeat_handler(btstack_timer_source_t *ts)
{
    ++counter;

    /* Blink the on-board LED (wired to the CYW43, not to an RP2350 GPIO) */
    led_on = !led_on;
    cyw43_arch_gpio_put(CYW43_WL_GPIO_LED_PIN, led_on);

    if (counter_notify_enabled && con_handle != HCI_CON_HANDLE_INVALID) {
        /* Notify from ATT_EVENT_CAN_SEND_NOW, when BTstack has buffer space */
        att_server_request_can_send_now_event(con_handle);
    }

    btstack_run_loop_set_timer(ts, kHeartbeatMs);
    btstack_run_loop_add_timer(ts);
}

} // namespace

int main()
{
    stdio_init_all();

    if (cyw43_arch_init() != 0) {
        printf("cyw43_arch_init failed\n");
        return -1;
    }

    l2cap_init();
    sm_init();

    att_server_init(profile_data, att_read_callback, att_write_callback);

    hci_event_registration.callback = &packet_handler;
    hci_add_event_handler(&hci_event_registration);
    att_server_register_packet_handler(packet_handler);

    heartbeat_timer.process = &heartbeat_handler;
    btstack_run_loop_set_timer(&heartbeat_timer, kHeartbeatMs);
    btstack_run_loop_add_timer(&heartbeat_timer);

    hci_power_control(HCI_POWER_ON);

    /* BTstack runs in the background; this core is free (UART work comes in phase 2) */
    while (true) {
        sleep_ms(1000);
    }
}
